-- =============================================================================
-- NubixPlus - esquema base (PostgreSQL 14+)
-- Generado a partir de las entidades JPA de nubixplus-lib.
--
-- Orden de creacion (respeta las FK):
--   permissions -> organizations -> users -> roles -> role_permissions
--   -> user_organizations -> user_organization_roles -> refresh_tokens
--   -> families -> categories -> products -> suppliers -> product_suppliers
--
-- Toda relacion N:M se modela con TRES tablas y una entidad intermedia propia
-- (role_permissions, user_organization_roles, product_suppliers). No hay
-- @ManyToMany en el modelo: nada de la N:M queda escondido detras del ORM.
--
-- Convenciones heredadas de las entidades:
--   * PK  : BIGINT IDENTITY (GenerationType.IDENTITY)
--   * LocalDateTime     -> TIMESTAMP(6) (sin zona horaria)
--   * @Enumerated(STRING) -> VARCHAR + CHECK
--   * BaseEntity        -> id, created_at, updated_at
--   * AuditableEntity   -> lo de BaseEntity mas created_by, updated_by,
--                          version (@Version)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- permissions  (Permission extends AuditableEntity)
-- -----------------------------------------------------------------------------
CREATE TABLE permissions (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(100) NOT NULL,            -- formato modulo:accion (users:create)
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(300),
    module      VARCHAR(60)  NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    -- AuditableEntity
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    created_by  VARCHAR(120),
    updated_by  VARCHAR(120),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_permissions          PRIMARY KEY (id),
    CONSTRAINT uk_permissions_code     UNIQUE (code)
);

CREATE INDEX ix_permissions_module ON permissions (module);

COMMENT ON TABLE  permissions      IS 'Permiso atomico del sistema, evaluado en @PreAuthorize';
COMMENT ON COLUMN permissions.code IS 'modulo:accion, ej. users:create';


-- -----------------------------------------------------------------------------
-- organizations  (Organization extends AuditableEntity) -- tenant
-- -----------------------------------------------------------------------------
CREATE TABLE organizations (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    legal_name      VARCHAR(200) NOT NULL,
    commercial_name VARCHAR(200),
    document_type   VARCHAR(20)  NOT NULL,
    document_number VARCHAR(20)  NOT NULL,        -- normalizado: solo digitos
    email           VARCHAR(150),
    phone           VARCHAR(30),
    address         VARCHAR(300),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    timezone        VARCHAR(60)           DEFAULT 'America/Santo_Domingo',
    currency        VARCHAR(3)            DEFAULT 'DOP',
    logo_url        VARCHAR(500),
    -- AuditableEntity
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    created_by      VARCHAR(120),
    updated_by      VARCHAR(120),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_organizations                     PRIMARY KEY (id),
    CONSTRAINT uk_organizations_document_number     UNIQUE (document_number),
    CONSTRAINT ck_organizations_document_type       CHECK (document_type IN ('RNC', 'CEDULA'))
);

-- La disponibilidad es binaria: boolean, no un enum de dos valores con su CHECK.
CREATE INDEX ix_organizations_active ON organizations (active);
-- ix_organizations_document_number del @Table es redundante: uk_organizations_document_number
-- ya crea el indice unico. Se omite a proposito.

COMMENT ON COLUMN organizations.document_number IS 'RNC (9 digitos) o cedula (11), solo digitos; viaja en X-Company-Document';


-- -----------------------------------------------------------------------------
-- users  (User extends AuditableEntity) -- identidad global, sin tenant
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email                 VARCHAR(180) NOT NULL,  -- siempre persistido en minusculas
    password_hash         VARCHAR(200) NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    phone                 VARCHAR(30),
    status                VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE',
    email_verified        BOOLEAN      NOT NULL DEFAULT FALSE,
    must_change_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at         TIMESTAMP(6),
    password_changed_at   TIMESTAMP(6),
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP(6),
    avatar_url            VARCHAR(500),
    locale                VARCHAR(10),
    -- AuditableEntity
    created_at            TIMESTAMP(6) NOT NULL,
    updated_at            TIMESTAMP(6) NOT NULL,
    created_by            VARCHAR(120),
    updated_by            VARCHAR(120),
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_users        PRIMARY KEY (id),
    CONSTRAINT uk_users_email  UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'PENDING_ACTIVATION', 'INACTIVE', 'LOCKED', 'SUSPENDED'))
);

CREATE INDEX ix_users_status ON users (status);

-- RECOMENDADO: los repositorios buscan con lower(email) (findByEmailIgnoreCase...,
-- y el fetch join del login). El indice unico plano NO se usa en esas consultas.
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));


-- -----------------------------------------------------------------------------
-- roles  (Role extends AuditableEntity)
--   organization_id NULL = rol de sistema, visible para todas las organizaciones
-- -----------------------------------------------------------------------------
CREATE TABLE roles (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(60)  NOT NULL,        -- MAYUSCULAS, ej. ORG_ADMIN
    name            VARCHAR(120) NOT NULL,
    description     VARCHAR(300),
    organization_id BIGINT,                       -- NULL => rol de sistema
    system_role     BOOLEAN      NOT NULL DEFAULT FALSE,
    -- AuditableEntity
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    created_by      VARCHAR(120),
    updated_by      VARCHAR(120),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_roles                    PRIMARY KEY (id),
    CONSTRAINT uk_roles_organization_code  UNIQUE (organization_id, code),
    CONSTRAINT fk_roles_organization       FOREIGN KEY (organization_id) REFERENCES organizations (id)
);

CREATE INDEX ix_roles_code         ON roles (code);
CREATE INDEX ix_roles_organization ON roles (organization_id);

-- RECOMENDADO: uk_roles_organization_code NO protege los roles de sistema, porque
-- en SQL dos filas con organization_id NULL nunca chocan. Este indice parcial si.
CREATE UNIQUE INDEX ux_roles_code_global ON roles (code) WHERE organization_id IS NULL;


-- -----------------------------------------------------------------------------
-- role_permissions  (RolePermission: tabla intermedia EXPLICITA Role <-> Permission)
--
-- La relacion N:M no la resuelve el ORM: la fila del medio es una entidad
-- (RolePermission extends BaseEntity), con su propio id y sus fechas. La unicidad
-- del par la garantiza uk_role_permissions, no la PK.
-- -----------------------------------------------------------------------------
CREATE TABLE role_permissions (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    role_id       BIGINT       NOT NULL,
    permission_id BIGINT       NOT NULL,
    -- BaseEntity (sin auditoria: un vinculo se otorga o se revoca)
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_role_permissions            PRIMARY KEY (id),
    CONSTRAINT uk_role_permissions            UNIQUE (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role       FOREIGN KEY (role_id)       REFERENCES roles (id)       ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions (id)
);

-- uk_role_permissions ya indexa role_id como columna lider, asi que ix_role_permissions_role
-- del @Table es redundante y se omite a proposito. El inverso si hace falta, para
-- responder "que roles usan este permiso".
CREATE INDEX ix_role_permissions_permission ON role_permissions (permission_id);


-- -----------------------------------------------------------------------------
